import { useRef, useState } from "react";
import { Button } from "@/components/ui/button";
import { configureImageGenerationKey } from "@/lib/persistent-agent-image-setup";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";

export function PersistentAgentImageSetup({
  onConfigured,
  onClose,
}: {
  onConfigured: () => void;
  onClose: () => void;
}): React.JSX.Element {
  const formRef = useRef<HTMLFormElement | null>(null);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState<string | null>(null);

  function close(): void {
    if (saving) return;
    formRef.current?.reset();
    setError(null);
    onClose();
  }

  return (
    <Dialog
      open
      onOpenChange={(open) => {
        if (!open) close();
      }}
    >
      <DialogContent showCloseButton={!saving}>
        <DialogHeader>
          <DialogTitle>Set up OpenAI API generation</DialogTitle>
          <DialogDescription>
            Add an OpenAI API key for the explicit, separately billed OpenAI API route. Codex uses your Codex sign-in
            instead.
          </DialogDescription>
        </DialogHeader>
        <form
          ref={formRef}
          autoComplete="off"
          className="space-y-4"
          onSubmit={async (event) => {
            event.preventDefault();
            if (saving) return;
            const form = event.currentTarget;
            const apiKey = String(new FormData(form).get("apiKey") ?? "").trim();
            if (!apiKey) return;
            setSaving(true);
            setError(null);
            const result = await configureImageGenerationKey(apiKey, window.roderDesktop.configureImageGeneration);
            form.reset();
            if (!result.configured) {
              setError(result.error);
            } else {
              onConfigured();
              onClose();
            }
            setSaving(false);
          }}
        >
          <label className="flex flex-col gap-1.5 text-base font-medium">
            OpenAI API key for image generation
            <input
              name="apiKey"
              type="password"
              autoComplete="off"
              required
              disabled={saving}
              spellCheck={false}
              className="h-10 rounded-lg border border-input bg-background px-3 outline-none focus-visible:ring-2 focus-visible:ring-ring"
            />
          </label>
          <p className="text-sm font-normal text-muted-foreground">
            Saving securely stores the key on this device. No image is generated by saving; choose Generate with OpenAI
            API separately when you want to start a billed job.
          </p>
          {error ? (
            <p role="alert" className="text-sm text-destructive">
              {error}
            </p>
          ) : null}
          <DialogFooter>
            <Button type="button" variant="ghost" disabled={saving} onClick={close}>
              Cancel
            </Button>
            <Button type="submit" disabled={saving}>
              {saving ? "Saving…" : "Save image key"}
            </Button>
          </DialogFooter>
        </form>
      </DialogContent>
    </Dialog>
  );
}
