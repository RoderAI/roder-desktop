const providerLogoAliases: Record<string, string> = {
  claude: "anthropic",
  codex: "openai",
  google: "gemini",
  googlegemini: "gemini",
  grok: "xai",
  mistralai: "mistral",
  opencodego: "opencode",
};

const providerLogoAliasMatchers = Object.entries(providerLogoAliases).map(([token, logoKey]) => ({ token, logoKey }));
const providerLogoMatchers = Object.entries(providerLogos).map(([token, logo]) => ({ token, logo }));

/** Brand images for providers without a vector mark. Matched against the normalized provider id. */
const providerImages: ReadonlyArray<{ token: string; src: string }> = [{ token: "rodercloud", src: roderAppIcon }];

/** Two-letter tiles for providers with no published mark, so every row keeps the same shape. */
const monogramOverrides: Readonly<Record<string, string>> = {
  fireworks: "FW",
  poolside: "PS",
  synthetic: "SY",
};

export function ProviderLogo({ provider }: { provider: string }): React.JSX.Element {
  const logo = providerLogoFor(provider);
  const image = providerImageFor(provider);

  return (
    <span
      className="grid size-5 shrink-0 place-items-center text-foreground"
      title={logo?.title ?? providerName(provider)}
      aria-hidden="true"
    >
      {logo ? (
        <svg viewBox={logo.viewBox ?? "0 0 24 24"} className="size-4" fill="currentColor" fillRule="evenodd">
          {logo.paths.map((path) => (
            <path key={path.d} d={path.d} clipRule={path.clipRule} fill={path.fill} opacity={path.opacity} />
          ))}
        </svg>
      ) : image ? (
        <img src={image} alt="" className="size-4 rounded-sm" draggable={false} />
      ) : (
        <span className="text-xs font-semibold leading-none">{monogramFor(provider)}</span>
      )}
    </span>
  );
}

function providerImageFor(provider: string): string | undefined {
  const normalizedProvider = provider.toLowerCase().replace(/[^a-z0-9]/g, "");
  return providerImages.find(({ token }) => containsProviderToken(normalizedProvider, token))?.src;
}

function monogramFor(provider: string): string {
  const normalized = provider.toLowerCase();
  const override = Object.entries(monogramOverrides).find(([token]) => normalized.includes(token));
  if (override) {
    return override[1];
  }
  return providerName(provider)
    .replace(/[^A-Za-z0-9]/g, "")
    .slice(0, 2)
    .toUpperCase();
}

function providerLogoFor(provider: string): ProviderLogoDefinition | undefined {
  const normalizedProvider = provider.toLowerCase().replace(/[^a-z0-9]/g, "");
  for (const { token, logoKey } of providerLogoAliasMatchers) {
    if (containsProviderToken(normalizedProvider, token)) {
      return providerLogos[logoKey];
    }
  }
  for (const { token, logo } of providerLogoMatchers) {
    if (containsProviderToken(normalizedProvider, token)) {
      return logo;
    }
  }
  return undefined;
}

function containsProviderToken(normalizedProvider: string, token: string): boolean {
  return normalizedProvider.indexOf(token) !== -1;
}
